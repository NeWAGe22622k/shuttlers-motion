// Scans src/ for every public asset path the film references and writes MISSING_ASSETS.md.
import fs from "node:fs";
import path from "node:path";

const walk = (d) => fs.readdirSync(d, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? walk(path.join(d, e.name)) : [path.join(d, e.name)]));
const refs = new Set();
for (const f of walk("src")) {
  const s = fs.readFileSync(f, "utf8");
  for (const m of s.matchAll(/["'`]((?:brand|screens|vehicles|audio|fonts|fx)\/[A-Za-z0-9_.\-]+)["'`]/g)) refs.add(m[1]);
}
// template paths built at runtime
for (const sub of ["latin", "latin-ext", "symbols"]) refs.add(`fonts/GoogleSans-${sub}.woff2`);
const list = [...refs].sort();
const missing = list.filter((p) => !fs.existsSync(path.join("public", p)));
const lines = [
  "# MISSING_ASSETS",
  "",
  `Generated by \`node tools/check_assets.mjs\` on ${new Date().toISOString().slice(0, 10)}.`,
  "",
  missing.length === 0
    ? "**No assets are missing.** No placeholder renders anywhere in any film."
    : `**${missing.length} missing** (each renders as a dashed placeholder showing its expected filename):`,
  "",
  ...missing.map((m) => `- [ ] public/${m}`),
  missing.length ? "" : "",
  "## Every asset the film references",
  "",
  ...list.map((p) => `- ${missing.includes(p) ? "MISSING" : "ok"} · public/${p}`),
  "",
  "## Notes",
  "",
  "- There is no Shuttlers wordmark file: \"Shuttlers\" / \"Shuttlers Pod\" is typeset in Google Sans 700 (as briefed).",
  "- `public/fonts/GoogleSans-*.woff2` are the exact Google Fonts files `@remotion/google-fonts/GoogleSans` points to, vendored because the render sandbox could not reach fonts.gstatic.com.",
  "- `public/fx/grain.png` is a generated, seeded film-grain tile (`python3 tools/make_grain.py`).",
  "- `public/fx/bayer4.png` is the 4×4 ordered-dither tile used with the grain on every PodVideo2-16x9 frame.",
  "- `public/audio/*` is generated by `python3 audio/build_audio.py`, `audio/build_edu_audio.py` and `audio/build_v2_16x9_audio.py` (never hand-placed).",
  "- PodVideo2-16x9 draws its own Pod, phone, map, keyboard and line icons (allowed by its brief); every other image is from `shuttlers-pod-assets.zip`.",
  "",
];
fs.writeFileSync("MISSING_ASSETS.md", lines.join("\n"));
console.log(`${list.length} referenced, ${missing.length} missing`);
